"""Порядковые числительные для слайдов «N-е место»: 9 → «девятое», 14 → «четырнадцатое».

«Место» — среднего рода, поэтому формы на -ое/-ье. Поддерживается 1–100: этого хватает с запасом
(в приложении число команд ограничено 50).
"""
from __future__ import annotations

from .errors import BackendError

_UNITS = {
    1: "первое", 2: "второе", 3: "третье", 4: "четвёртое", 5: "пятое",
    6: "шестое", 7: "седьмое", 8: "восьмое", 9: "девятое",
}
_TEENS = {
    10: "десятое", 11: "одиннадцатое", 12: "двенадцатое", 13: "тринадцатое", 14: "четырнадцатое",
    15: "пятнадцатое", 16: "шестнадцатое", 17: "семнадцатое", 18: "восемнадцатое", 19: "девятнадцатое",
}
# Круглые десятки как порядковые («двадцатое») и как количественные в составе («двадцать первое»).
_TENS_ORDINAL = {
    20: "двадцатое", 30: "тридцатое", 40: "сороковое", 50: "пятидесятое",
    60: "шестидесятое", 70: "семидесятое", 80: "восьмидесятое", 90: "девяностое",
}
_TENS_CARDINAL = {
    20: "двадцать", 30: "тридцать", 40: "сорок", 50: "пятьдесят",
    60: "шестьдесят", 70: "семьдесят", 80: "восемьдесят", 90: "девяносто",
}


def ordinal_place(number: int) -> str:
    """Порядковое числительное среднего рода строчными: 1 → «первое», 23 → «двадцать третье»."""
    if not 1 <= number <= 100:
        raise BackendError(
            "INVALID_ARGUMENT",
            f"Не умею писать место {number} словами: поддерживаются места от 1 до 100.",
        )
    if number == 100:
        return "сотое"
    if number in _UNITS:
        return _UNITS[number]
    if number in _TEENS:
        return _TEENS[number]
    tens, units = (number // 10) * 10, number % 10
    if units == 0:
        return _TENS_ORDINAL[tens]
    return f"{_TENS_CARDINAL[tens]} {_UNITS[units]}"


# Сколько знаков помещается в поле «НОМЕР» слайда-шаблона в одну строку при шрифте шаблона: проверено
# на реальном слайде — «ЧЕТЫРНАДЦАТОЕ» (13) помещается, «ДВАДЦАТЬ ВОСЬМОЕ» (16) упирается в края слайда,
# «ВОСЕМЬДЕСЯТ ВОСЬМОЕ» (19) переносится на вторую строку и налезает на слово «МЕСТО».
MAX_SINGLE_LINE_CHARS = 13


def ordinal_font_scale(text: str) -> float:
    """Во сколько раз уменьшить шрифт шаблона, чтобы текст остался в одной строке (1.0 — не трогать)."""
    return min(1.0, MAX_SINGLE_LINE_CHARS / len(text))
